# Inisialisasi variabel awal
nama = "Fajar"
umur = 19
berat = 54.5
terdaftar = True

# 1 & 2. Menampilkan nilai dan tipe data masing-masing variabel
print("=== Output Awal ===")
print("Nama      :", nama, "| Tipe Data:", type(nama))
print("Umur      :", umur, "| Tipe Data:", type(umur))
print("Berat     :", berat, "| Tipe Data:", type(berat))
print("Terdaftar :", terdaftar, "| Tipe Data:", type(terdaftar))

print("\n" + "="*30 + "\n")

# 3. Mengubah nilai umur menjadi 20
umur = 20
print("=== Setelah Perubahan Nilai Umur ===")
print("Umur baru :", umur, "| Tipe Data:", type(umur))
