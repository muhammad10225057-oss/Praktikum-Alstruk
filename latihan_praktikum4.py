# 1. Simpan poin awal
poin = 100
print(f"Nilai awal : {poin}")

# 2. Tambahkan 25 poin
poin += 25
print(f"poin += 25  : {poin}")

# 3. Kurangi 10 poin
poin -= 10
print(f"poin -= 10  : {poin}")

# 4. Kalikan poin dengan 2
poin *= 2
print(f"poin *= 2   : {poin}")

# 5. Bagi poin dengan 2
poin /= 2
print(f"poin /= 2   : {poin}")